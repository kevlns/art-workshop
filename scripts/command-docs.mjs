import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

const root=new URL('../',import.meta.url);
export function skillDocs(){
  const manifest=JSON.parse(readFileSync(new URL('v-cli.plugin.json',root),'utf8'));
  const instructions=readFileSync(new URL('AGENTS.md',root),'utf8').replace(/\[([^\]]+)\]\((?![a-z]+:|#)([^)]+)\)/gi,'$1');
  return `---\nname: art-workshop\ndescription: ${JSON.stringify(manifest.description)}\n---\n\n随包规范通过 \`v-cli agent docs art\` 读取；使用说明与数据契约通过 \`v-cli art agent docs\` 读取。\n\n`+instructions;
}
export function commandDocs(){
  const manifest=JSON.parse(readFileSync(new URL('v-cli.plugin.json',root),'utf8'));
  const lines=['# Vant 美术工坊命令参考','','<!-- Generated by scripts/command-docs.mjs; edit v-cli.plugin.json. -->','','## 定位','','本文件由插件清单生成。`npm run docs:generate` 更新，`npm run docs:check` 检查漂移。','','## 调用方式','','`v-cli art` 路由到同一工具；直接调用可用 `art-workshop`。标识、路径占位符须替换为真实值。','','### 全局选项',''];
  for(const option of manifest.agent.globalOptions)lines.push(`- \`${option.flags}\`：${option.description}`);
  lines.push('','## 执行约束','','相对计划、输入和报告路径以 workspace 为基准；运行批次以 output 为基准。参考导入的源文件建议使用绝对路径。查询与预演不初始化参考目录。','','冻结计划不能覆盖 project/job/core/backend/explore。`--all-variants` 与 `--variant` 互斥。`--retry-run` 只用于原计划的明确失败项，不能混用 dry/item/variant/offset/limit。远程恢复只用 `task resume`，不会补发未提交项。','','前台运行也登记 taskId；后台启动成功仅表示收到执行身份。状态、停止确认和实际产物分别核对。详见 [任务控制](troubleshooting.md)、[模型架构](model-architecture.md) 和 [部署](deployment.md)。','');
  lines.push('## 参数与输出','');
  for(const command of manifest.agent.commands){
    lines.push(`### ${command.path.join(' ')}`,'',command.description,'','```sh',command.usage.replace(/^art-workshop\b/,'v-cli art'),'```','');
    for(const argument of command.arguments??[])lines.push(`- 位置参数 \`${argument.name}\`：${argument.description}${argument.required?'（必填）':''}`);
    for(const option of command.options??[])lines.push(`- \`${option.flags}\`：${option.description}`);
    lines.push('');
    for(const safety of command.safety??[])lines.push(`- ${safety}`);
    lines.push('');
  }
  lines.push('## 结果验证','','按任务身份、停止证据和实际产物核验；只读检查不证明真实出图。','','## 参考资料','','[使用说明](../README.md) · [文档规范](documentation.md)');
  return lines.join('\n').trimEnd()+'\n';
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  writeFileSync(new URL('docs/commands.md',root),commandDocs());
  writeFileSync(new URL('skills/art-workshop/SKILL.md',root),skillDocs());
  console.log('docs/commands.md and skills/art-workshop/SKILL.md generated');
}
