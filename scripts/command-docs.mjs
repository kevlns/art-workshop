import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

const root=new URL('../',import.meta.url);
export function skillDocs(){return readFileSync(new URL('skills/art-workshop/SKILL.md',root),'utf8');}
export function commandDocs(){
  const manifest=JSON.parse(readFileSync(new URL('v-cli.plugin.json',root),'utf8'));
  const lines=['# Vant 美术工坊命令参考','','<!-- Generated by scripts/command-docs.mjs; edit v-cli.plugin.json. -->','','## 定位','','本文件由插件清单生成。`npm run docs:generate` 更新，`npm run docs:check` 检查漂移。','','## 调用方式','','`v-cli art` 路由到同一工具；直接调用可用 `art-workshop`。标识、路径占位符须替换为真实值。','','### 全局选项',''];
  for(const option of manifest.agent.globalOptions)lines.push(`- \`${option.flags}\`：${option.description}`);
  lines.push('','## 执行约束','','`image` 与 `video` 是独立二级通道。图片可使用 `v-cli art image ...`，旧图片根命令与原 `art.*` 能力身份保留。新 SDK 暴露 `art.image-*` 和 `art.video-*`；已安装旧版 v-cli 不会自动获得新能力。','','图片的相对计划、输入和报告路径以 workspace 为基准；运行批次以 output 为基准。参考导入的源文件建议使用绝对路径。查询与预演不初始化参考目录。','','视频的 `--workspace` 必须指向工程根目录，数据在 `.vant/video`、设置在 `.vant/config/video.json`；不能传图片工坊存储子目录。`--input` 只能读取该工程内的 JSON 对象文件。先读取 `video describe` 中的业务 schema，保留真实 revision/expectedRevision 与稳定 requestId。','','所有视频写命令必须传 `--operation`。非 video-UUID 的上层身份会稳定映射成 video-UUID，并在回执保留 originOperationId。同身份同请求只重读回执；未知结果与未决指纹使用 DSH/CLI 共享目录阻止换入口重投。`video execution status --operation <id>` 只读核对原回执；`submitted` 只证明提交身份，不证明视频已完成。','','冻结图片计划不能覆盖 project/job/core/backend/explore。`--all-variants` 与 `--variant` 互斥。`--retry-run` 只用于原计划的明确失败项，不能混用 dry/item/variant/offset/limit。图片远程恢复只用 `task resume`，不会补发未提交项。','','前台图片运行也登记 taskId；后台启动成功仅表示收到执行身份。状态、停止确认和实际产物分别核对。详见 [任务控制](troubleshooting.md)、[模型架构](model-architecture.md) 和 [部署](deployment.md)。','');
  lines.push('## 参数与输出','');
  for(const command of manifest.agent.commands){
    lines.push(`### ${command.path.join(' ')}`,'',command.description,'','```sh',command.usage.replace(/^art-workshop\b/,'v-cli art'),'```','');
    if(command.capabilityId)lines.push(`结构化能力：\`${command.capabilityId}\`。`,'');
    for(const argument of command.arguments??[])lines.push(`- 位置参数 \`${argument.name}\`：${argument.description}${argument.required?'（必填）':''}`);
    for(const option of command.options??[])lines.push(`- \`${option.flags}\`：${option.description}`);
    lines.push('');
    for(const safety of command.safety??[])lines.push(`- ${safety}`);
    lines.push('');
  }
  lines.push('## 结果验证','','按任务身份、停止证据和实际产物核验；只读检查不证明真实出图。','','## 参考资料','','[使用说明](../README.md) · [文档规范](documentation.md)');
  return lines.join('\n').trimEnd()+'\n';
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  writeFileSync(new URL('docs/commands.md',root),commandDocs());
  console.log('docs/commands.md generated');
}
